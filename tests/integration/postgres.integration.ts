// Runs the PostgreSQL engine against the real server started by compose.yaml:
//   docker compose -f tests/integration/compose.yaml up -d --wait
//   node --run test:integration
import assert from "node:assert/strict";
import { describe, test } from "node:test";

import { Client } from "pg";

import { connectReadOnly, introspectPostgres, type PostgresConnectionOptions } from "../../lib/engines/postgres/introspect.ts";
import { schemaHash } from "../../lib/model/hash.ts";
import type { Snapshot, Table } from "../../lib/model/snapshot.ts";

const PORT = 33116;

function options(overrides: Partial<PostgresConnectionOptions> = {}): PostgresConnectionOptions {
	return {
		host: "127.0.0.1",
		port: PORT,
		user: "postgres",
		password: "heydb-test",
		database: "legacy",
		schemas: ["public", "billing"],
		...overrides,
	};
}

function reader(overrides: Partial<PostgresConnectionOptions> = {}): PostgresConnectionOptions {
	return options({ user: "heydb_reader", password: "reader-pass", ...overrides });
}

function table(snapshot: Snapshot, schema: string, name: string): Table {
	const found = snapshot.databases[0]?.schemas.find((s) => s.name === schema)?.tables.find((t) => t.name === name);
	assert.ok(found, `expected table ${schema}.${name}`);
	return found;
}

describe("introspectPostgres against PostgreSQL 16", () => {
	let snapshot: Snapshot;

	test("captures the connected database with the requested schemas and detects the engine", async () => {
		snapshot = await introspectPostgres(options());
		assert.equal(snapshot.engine.kind, "postgresql");
		assert.match(snapshot.engine.version, /^16\.\d+/);
		assert.deepEqual(
			snapshot.databases.map((d) => [d.name, d.schemas.map((s) => s.name)]),
			[["legacy", ["billing", "public"]]],
		);
		assert.deepEqual(snapshot.warnings, []);
	});

	test("lists tables, views, materialized views and partitioned tables, but not partitions", () => {
		const publicSchema = snapshot.databases[0]?.schemas.find((s) => s.name === "public");
		assert.deepEqual(
			publicSchema?.tables.map((t) => `${t.name}:${t.kind}`),
			[
				"MixedCase:table",
				"events:table",
				"order_lines:table",
				"order_totals:view",
				"orders:table",
				"paid_orders:view",
				"shipments:table",
				"v1.old_orders:table",
			],
		);
	});

	test("keeps quoted identifiers exactly as created", () => {
		const mixed = table(snapshot, "public", "MixedCase");
		assert.deepEqual(mixed.columns.map((c) => c.name), ["Id", "DisplayName"]);
		assert.deepEqual(mixed.primaryKey, ["Id"]);
	});

	test("reads view and materialized view definitions with schema-qualified names", () => {
		assert.match(table(snapshot, "public", "paid_orders").viewDefinition ?? "", /FROM public\.orders\s+WHERE status = 'paid'::public\.order_status;$/);
		assert.match(table(snapshot, "public", "order_totals").viewDefinition ?? "", /sum\(total\) AS total\s+FROM public\.orders/);
		assert.equal(table(snapshot, "public", "orders").viewDefinition, null);
		assert.deepEqual(table(snapshot, "public", "order_totals").indexes, [
			{ name: "uq_order_totals_customer", columns: ["customer_id"], unique: true, method: "btree" },
		]);
	});

	test("keeps the primary key in key order, not column order", () => {
		assert.deepEqual(table(snapshot, "public", "order_lines").primaryKey, ["line_no", "order_id"]);
	});

	test("reads a cross-schema foreign key with its actions", () => {
		assert.deepEqual(table(snapshot, "public", "orders").foreignKeys, [
			{
				name: "fk_orders_customer",
				columns: ["customer_id"],
				references: { database: "legacy", schema: "billing", table: "customers", columns: ["id"] },
				onDelete: "RESTRICT",
				onUpdate: "CASCADE",
			},
		]);
	});

	test("reads a composite foreign key in key order", () => {
		assert.deepEqual(table(snapshot, "public", "shipments").foreignKeys, [
			{
				name: "fk_shipments_line",
				columns: ["line_no", "order_id"],
				references: { database: "legacy", schema: "public", table: "order_lines", columns: ["line_no", "order_id"] },
				onDelete: "SET NULL",
				onUpdate: "NO ACTION",
			},
		]);
	});

	test("reads identity, serial and stored generated columns", () => {
		const column = (schema: string, tableName: string, name: string) =>
			table(snapshot, schema, tableName).columns.find((c) => c.name === name);
		assert.deepEqual(
			[column("billing", "customers", "id")?.default, column("billing", "customers", "id")?.autoIncrement],
			["GENERATED ALWAYS AS IDENTITY", true],
		);
		assert.equal(column("public", "orders", "id")?.default, "GENERATED BY DEFAULT AS IDENTITY");
		assert.deepEqual(
			[column("public", "shipments", "id")?.default, column("public", "shipments", "id")?.autoIncrement],
			["nextval('public.shipments_id_seq'::regclass)", true],
		);
		const lineTotal = column("public", "order_lines", "line_total");
		assert.deepEqual([lineTotal?.generated, lineTotal?.default], [{ expression: "((quantity)::numeric * unit_price)", stored: true }, null]);
	});

	test("reads an enum column with its labels, defaults, comments and explicit collations", () => {
		const orders = table(snapshot, "public", "orders");
		const status = orders.columns.find((c) => c.name === "status");
		assert.equal(status?.type, "public.order_status enum('draft','paid','cancelled','it''s complicated')");
		assert.equal(status?.default, "'draft'::public.order_status");
		assert.equal(orders.comment, "Customer orders");
		assert.equal(orders.columns.find((c) => c.name === "total")?.comment, "Includes VAT");
		const customers = table(snapshot, "billing", "customers");
		assert.equal(customers.comment, "Billing customers");
		assert.equal(customers.columns.find((c) => c.name === "email")?.collation, "C");
		assert.equal(customers.columns.find((c) => c.name === "name")?.collation, null, "the type's own collation is not repeated");
		assert.deepEqual(customers.indexes, [{ name: "uq_customers_email", columns: ["email"], unique: true, method: "btree" }]);
		assert.ok(orders.indexes.some((i) => i.name === "idx_orders_notes" && i.method === "gin" && /to_tsvector/.test(i.columns[0] ?? "")));
	});

	test("estimates rows from the statistics, null when never analyzed", () => {
		assert.equal(table(snapshot, "public", "orders").rowEstimate, 2);
		assert.equal(table(snapshot, "public", "events").rowEstimate, 3);
		assert.equal(table(snapshot, "public", "shipments").rowEstimate, null);
		assert.equal(table(snapshot, "public", "paid_orders").rowEstimate, null);
	});

	test("reads triggers and routines, without aggregates or extension functions", () => {
		assert.deepEqual(table(snapshot, "public", "orders").triggers, [
			{ name: "trg_orders_clamp", timing: "BEFORE", events: ["INSERT", "UPDATE"] },
		]);
		assert.deepEqual(snapshot.databases[0]?.schemas.find((s) => s.name === "public")?.routines, [
			{ name: "close_order", kind: "procedure" },
			{ name: "order_count", kind: "function" },
			{ name: "orders_clamp_total", kind: "function" },
		]);
	});

	test("produces the same hash on a second capture", async () => {
		assert.equal(schemaHash(await introspectPostgres(options())), schemaHash(snapshot));
	});

	test("a role's own search_path, DateStyle and TimeZone do not change what is captured", async () => {
		// heydb_reader has search_path billing, public; DateStyle SQL, DMY; TimeZone Asia/Tokyo.
		const asReader = await introspectPostgres(reader());
		assert.equal(schemaHash(asReader), schemaHash(snapshot));
	});

	test("captures every non-system schema when none is requested", async () => {
		const all = await introspectPostgres(options({ schemas: null }));
		assert.deepEqual(all.databases[0]?.schemas.map((s) => s.name), ["billing", "public", "secret"]);
	});

	test("a read-only role sees the structure of every schema, and heydb says which it cannot query", async () => {
		const all = await introspectPostgres(reader({ schemas: null }));
		assert.deepEqual(all.databases[0]?.schemas.map((s) => s.name), ["billing", "public", "secret"]);
		assert.deepEqual(
			all.warnings.map((w) => `${w.code}:${w.target}`),
			["schema_not_usable:legacy.billing", "schema_not_usable:legacy.secret"],
		);
		assert.ok(table(all, "secret", "api_keys"), "pg_catalog lists it even without USAGE");
	});

	test("warns about requested schemas that do not exist, names matched exactly", async () => {
		const some = await introspectPostgres(reader({ schemas: ["public", "Public", "missing"] }));
		assert.deepEqual(some.databases[0]?.schemas.map((s) => s.name), ["public"]);
		assert.deepEqual(
			some.warnings.map((w) => `${w.code}:${w.target}`),
			["schema_not_visible:legacy.Public", "schema_not_visible:legacy.missing"],
		);
	});

	test("opens a read-only session: even a superuser cannot write through it", async () => {
		const client = await connectReadOnly(options());
		try {
			await assert.rejects(
				client.query("INSERT INTO public.orders (customer_id) VALUES (1)"),
				/cannot execute INSERT in a read-only transaction/,
			);
		} finally {
			await client.end();
		}
	});

	test("reports a wrong password clearly, without repeating it", async () => {
		await assert.rejects(introspectPostgres(options({ password: "wrong-Secret-42" })), (error: Error) => {
			assert.match(
				error.message,
				/^postgresql: cannot connect to 127\.0\.0\.1:33116 as postgres \(database "legacy"\): password authentication failed for user "postgres"$/,
			);
			assert.equal(`${String(error)} ${String(error.stack)} ${JSON.stringify(error)}`.includes("wrong-Secret-42"), false);
			return true;
		});
	});

	test("reports a database that does not exist", async () => {
		await assert.rejects(introspectPostgres(options({ database: "nope" })), /^Error: postgresql: cannot connect .*database "nope" does not exist/);
	});
});

test("closes the connection when the session cannot be made read-only", async (t) => {
	// Simulates a server or proxy that rejects the session settings.
	const prototype = Client.prototype as unknown as Record<string, (...args: unknown[]) => unknown>;
	const realQuery = prototype.query!;
	const end = t.mock.method(Client.prototype, "end");
	t.mock.method(prototype, "query", function (this: unknown, sql: unknown, ...rest: unknown[]) {
		if (typeof sql === "string" && sql.includes("set_config")) return Promise.reject(new Error("syntax error"));
		return realQuery.call(this, sql, ...rest);
	});
	await assert.rejects(introspectPostgres(options()), /^Error: postgresql: cannot open a read-only session on 127\.0\.0\.1:33116: syntax error/);
	assert.equal(end.mock.callCount(), 1, "the connection is closed exactly once");
});

test("reports an unreachable server clearly", async () => {
	await assert.rejects(
		introspectPostgres(options({ port: 1, connectTimeoutMs: 2000 })),
		/^Error: postgresql: cannot connect to 127\.0\.0\.1:1 as postgres \(database "legacy"\): /,
	);
});
