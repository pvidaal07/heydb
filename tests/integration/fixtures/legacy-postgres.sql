-- A read-only role like the one heydb recommends: USAGE and SELECT on public
-- only. billing and secret are not usable by it. Its own session settings
-- differ on purpose (search_path, DateStyle, TimeZone).
CREATE ROLE heydb_reader LOGIN PASSWORD 'reader-pass';
GRANT USAGE ON SCHEMA public TO heydb_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO heydb_reader;
ALTER ROLE heydb_reader SET search_path = billing, public;
ALTER ROLE heydb_reader SET "DateStyle" = 'SQL, DMY';
ALTER ROLE heydb_reader SET "TimeZone" = 'Asia/Tokyo';
