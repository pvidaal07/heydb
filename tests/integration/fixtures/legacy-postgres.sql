-- A small "legacy" PostgreSQL database with the cases heydb must handle.
-- Loaded by the postgres16 container in tests/integration/compose.yaml on
-- first start, connected to the database "legacy" (POSTGRES_DB). It must stay
-- valid on PostgreSQL 14+.

CREATE SCHEMA billing;
CREATE SCHEMA secret;

-- An extension puts dozens of functions into public; they belong to the
-- extension, not to this application, and heydb leaves them out.
CREATE EXTENSION citext SCHEMA public;

CREATE TYPE public.order_status AS ENUM ('draft', 'paid', 'cancelled', 'it''s complicated');

-- Customers live in another schema: public.orders points here (cross-schema FK).
-- The date and timestamptz defaults print differently under another DateStyle
-- or TimeZone: heydb pins its session settings so they never change the hash.
CREATE TABLE billing.customers (
	id integer GENERATED ALWAYS AS IDENTITY,
	email varchar(255) COLLATE "C" NOT NULL,
	name text,
	status smallint NOT NULL DEFAULT 1,
	valid_from date NOT NULL DEFAULT '2020-01-31',
	created_at timestamptz NOT NULL DEFAULT '2020-01-31 10:00:00+00',
	PRIMARY KEY (id),
	CONSTRAINT uq_customers_email UNIQUE (email)
);
COMMENT ON TABLE billing.customers IS 'Billing customers';
COMMENT ON COLUMN billing.customers.status IS '1=active 2=blocked 3=deleted';

CREATE TABLE public.orders (
	id bigint GENERATED BY DEFAULT AS IDENTITY,
	customer_id integer NOT NULL,
	total numeric(10,2) NOT NULL DEFAULT 0,
	status public.order_status NOT NULL DEFAULT 'draft',
	notes text,
	PRIMARY KEY (id),
	CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES billing.customers (id)
		ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX idx_orders_customer ON public.orders (customer_id);
CREATE INDEX idx_orders_notes ON public.orders USING gin (to_tsvector('simple', coalesce(notes, '')));
COMMENT ON TABLE public.orders IS 'Customer orders';
COMMENT ON COLUMN public.orders.total IS 'Includes VAT';

-- Primary key order (line_no, order_id) differs from column order, and a
-- stored generated column.
CREATE TABLE public.order_lines (
	order_id bigint NOT NULL,
	line_no smallint NOT NULL,
	product_code varchar(20) NOT NULL,
	quantity integer NOT NULL DEFAULT 1,
	unit_price numeric(10,2) NOT NULL,
	line_total numeric(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
	PRIMARY KEY (line_no, order_id),
	CONSTRAINT fk_lines_order FOREIGN KEY (order_id) REFERENCES public.orders (id) ON DELETE CASCADE
);

-- Composite foreign key with SET NULL, and the old serial idiom.
CREATE TABLE public.shipments (
	id serial PRIMARY KEY,
	line_no smallint,
	order_id bigint,
	shipped_at timestamptz,
	CONSTRAINT fk_shipments_line FOREIGN KEY (line_no, order_id) REFERENCES public.order_lines (line_no, order_id)
		ON DELETE SET NULL
);

-- Quoted identifiers keep their case, and a name may contain a dot.
CREATE TABLE public."MixedCase" (
	"Id" integer PRIMARY KEY,
	"DisplayName" text
);
CREATE TABLE public."v1.old_orders" (
	id integer PRIMARY KEY
);

CREATE VIEW public.paid_orders AS
	SELECT id, customer_id, total FROM public.orders WHERE status = 'paid';

CREATE MATERIALIZED VIEW public.order_totals AS
	SELECT customer_id, sum(total) AS total FROM public.orders GROUP BY customer_id;
CREATE UNIQUE INDEX uq_order_totals_customer ON public.order_totals (customer_id);

-- A partitioned table: heydb lists the parent, not each partition.
CREATE TABLE public.events (
	id bigint NOT NULL,
	happened_on date NOT NULL,
	payload jsonb,
	PRIMARY KEY (id, happened_on)
) PARTITION BY RANGE (happened_on);
CREATE TABLE public.events_2026 PARTITION OF public.events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE TABLE public.events_2027 PARTITION OF public.events FOR VALUES FROM ('2027-01-01') TO ('2028-01-01');

CREATE FUNCTION public.orders_clamp_total() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	NEW.total := greatest(NEW.total, 0);
	RETURN NEW;
END
$$;
CREATE TRIGGER trg_orders_clamp BEFORE INSERT OR UPDATE ON public.orders
	FOR EACH ROW EXECUTE FUNCTION public.orders_clamp_total();

CREATE PROCEDURE public.close_order(p_id bigint) LANGUAGE sql AS $$
	UPDATE public.orders SET status = 'cancelled' WHERE id = p_id
$$;

CREATE FUNCTION public.order_count() RETURNS bigint LANGUAGE sql STABLE AS $$
	SELECT count(*) FROM public.orders
$$;

-- Aggregates are not captured as routines.
CREATE AGGREGATE public.concat_all (text) (SFUNC = textcat, STYPE = text, INITCOND = '');

CREATE TABLE secret.api_keys (
	id integer PRIMARY KEY
);

